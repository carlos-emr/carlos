def profile_parts(profile: str) -> tuple[str, str]:
    """The origin and growth series of one profile."""
    if profile not in PROFILES:
        raise ValueError("unknown export scaling profile")
    origin, _, series = profile.partition("-")
    return origin, series


def case_definitions(profile: str) -> list[dict]:
    """The three cases of one profile's growth series."""
    origin, series = profile_parts(profile)
    return [
        {"label": label, "origin": origin, "patients": patients, "records": records}
        for label, patients, records in SERIES[series]
    ]


def case_budget(budget: dict, patients: int, notes: int) -> dict:
    """Linear budget of one case: a fixed command cost plus per-patient and per-note growth."""
    if type(patients) is not int or type(notes) is not int or patients < 1 or notes < patients:
        raise ValueError("invalid case size")
    return {
        "statements": budget["fixedStatements"]
        + budget["statementsPerPatient"] * patients
        + budget["statementsPerNote"] * notes,
        "privilegeStatements": budget["fixedPrivilegeStatements"]
        + budget["privilegeStatementsPerPatient"] * patients
        + budget["privilegeStatementsPerNote"] * notes,
        "elapsedSeconds": budget["fixedSeconds"]
        + budget["secondsPerPatient"] * patients
        + budget["secondsPerNote"] * notes,
        "serviceRssBytes": budget["serviceRssMiB"] * MIB,
        "cliRssBytes": budget["cliRssMiB"] * MIB,
    }


def functional_failures(case: dict) -> list[str]:
    """Outcome failures that make every number of the case meaningless; the profile stops."""
    failures = []
    outcome = case.get("export") or {}
    result = outcome.get("result") if isinstance(outcome, dict) else None
    if case.get("exitCode") != 0:
        failures.append("EXPORT_PROCESS_FAILED")
    if not isinstance(result, dict) or outcome.get("accepted") != 1:
        failures.append("EXPORT_EVIDENCE_MISSING")
        return failures
    if result.get("state") != "READY" or result.get("complete") is not True:
        failures.append("EXPORT_NOT_READY")
    if result.get("blockedPatients") != 0 or result.get("heldBack") is not False:
        failures.append("EXPORT_PATIENTS_HELD")
    if (
        result.get("processedPatients") != case.get("patients")
        or result.get("totalPatients") != case.get("patients")
    ):
        failures.append("EXPORT_PATIENT_COUNT")
    package = case.get("package")
    if failures:
        return failures
    if not isinstance(package, dict):
        failures.append("EXPORT_EVIDENCE_MISSING")
    elif (
        package.get("xmlMembers") != case["patients"]
        or package.get("patientRecords") != case["patients"]
        or package.get("clinicalNotes") != case["notes"]
        or package.get("laboratoryResults") != case["labs"]
    ):
        failures.append("EXPORT_RECORD_COUNT")
    return failures


def budget_failures(case: dict, budget: dict) -> list[str]:
    """Measured budgets of one fully verified case; recorded, and later cases still run."""
    limits = case_budget(budget, case["patients"], case["notes"])
    measured = (
        ("STATEMENT_BUDGET", case.get("budgetedStatements"), limits["statements"]),
        ("PRIVILEGE_STATEMENT_BUDGET", case.get("privilegeStatements"), limits["privilegeStatements"]),
        ("ELAPSED_BUDGET", case.get("elapsedSeconds"), limits["elapsedSeconds"]),
        ("SERVICE_RSS_BUDGET", case.get("serviceJvmPeakRssBytes"), limits["serviceRssBytes"]),
        ("CLI_RSS_BUDGET", case.get("cliPeakRssBytes"), limits["cliRssBytes"]),
    )
    failures = []
    for code, value, limit in measured:
        # A missing or negative measurement is never a pass; it fails like an exceeded budget.
        if type(value) not in (int, float) or value < 0 or value > limit:
            failures.append(code)
    return failures


def marginal(cases: list[dict], key: str, size: str) -> float | None:
    """Growth of ``key`` per unit of ``size`` from the smallest to the largest case of a series."""
    series = sorted(
        (case for case in cases if isinstance(case.get(key), (int, float))),
        key=lambda case: case[size],
    )
    if len(series) < 2 or series[-1][size] == series[0][size]:
        return None
    return (series[-1][key] - series[0][key]) / (series[-1][size] - series[0][size])


def evaluate_marginal(cases: list[dict], budget: dict, *, required: frozenset) -> dict:
    """Per-note and per-patient growth, independent of the fixed command cost of each export.

    ``required`` names the series a complete profile must measure; a growth value that cannot be
    computed for a required series fails like an exceeded budget. A diagnostic subset passes
    an empty set and records whatever it could measure.
    """
    values, limits, failures = {}, {}, []
    for name, (series, key, size, limit, code) in MARGINAL.items():
        prefix = "chart-" if series == "charts" else "patients-"
        value = marginal([case for case in cases if case["label"].startswith(prefix)], key, size)
        values[name] = value
        limits[name] = budget[limit]
        if value is None:
            if series in required:
                failures.append(code)
        elif value > budget[limit]:
            failures.append(code)
    return {"values": values, "budgets": limits, "failures": failures}


def cgroup_limits(root: Path = Path("/sys/fs/cgroup")) -> dict:
    """The runtime's effective memory and CPU limits, in cgroup v2 notation.

    CI runners use the unified (v2) hierarchy. A cgroup v1 host (a developer machine) exposes the
    same limits through the memory and cpu controllers; the version is recorded with them.
    """
    if (root / "cgroup.controllers").is_file():
        return {
            "version": 2,
            "memoryMax": (root / "memory.max").read_text().strip(),
            "cpuMax": (root / "cpu.max").read_text().split(),
        }
    quota = (root / "cpu/cpu.cfs_quota_us").read_text().strip()
    period = (root / "cpu/cpu.cfs_period_us").read_text().strip()
    return {
        "version": 1,
        "memoryMax": (root / "memory/memory.limit_in_bytes").read_text().strip(),
        "cpuMax": ["max" if quota == "-1" else quota, period],
    }


def require_limits(limits: dict, memory_mib: int | None, cpus: int | None) -> None:
    cpu_max = limits["cpuMax"]
    if (
        memory_mib is not None
        and limits["memoryMax"] != str(memory_mib * MIB)
        or cpus is not None
        and (
            len(cpu_max) != 2
            or not all(value.isdecimal() for value in cpu_max)
            or int(cpu_max[0]) != cpus * int(cpu_max[1])
        )
    ):
        raise RuntimeError("effective cgroup limits do not match the measured workload contract")


def cgroup_counters(root: Path = Path("/sys/fs/cgroup")) -> dict:
    """OOM and CPU counters of the runtime cgroup (v2 memory.events, or v1 memory.oom_control)."""

    def read(path: Path) -> dict:
        return dict(line.split() for line in path.read_text().splitlines())

    if (root / "cgroup.controllers").is_file():
        return {name: read(root / name) for name in ("memory.events", "cpu.stat")}
    return {
        "memory.oom_control": read(root / "memory/memory.oom_control"),
        "cpu.stat": read(root / "cpu/cpu.stat"),
    }


def require_no_oom(initial: dict, current: dict) -> None:
    """No OOM kill in the runtime cgroup between two snapshots, and no counter reset."""
    if "memory.events" in initial:
        GATE.require_no_cgroup_oom(initial, current)
        return
    values = [
        snapshot.get("memory.oom_control", {}).get("oom_kill") for snapshot in (initial, current)
    ]
    if any(not isinstance(value, str) or not value.isdecimal() for value in values):
        raise RuntimeError("required actual cgroup OOM counters are unavailable")
    if values[0] != values[1] or current["memory.oom_control"].get("under_oom") != "0":
        raise RuntimeError("a measured profile caused a cgroup OOM event or counters reset")


def is_export_command(command: list[bytes], provider: str) -> bool:
    """The delegated engine JVM of a new export; never the capability probe or a download."""
    if (
        not command
        or Path(os.fsdecode(command[0])).name != "java"
        or EXPORT_MAIN not in command
        or b"--capabilities" in command
    ):
        return False
    for key, value in ((b"--operation", b"export"), (b"--provider", provider.encode())):
        if command.count(key) != 1:
            return False
        index = command.index(key)
        if index + 1 >= len(command) or command[index + 1] != value:
            return False
    return True


def is_cli_command(command: list[bytes]) -> bool:
    """The root carlos-ctl adapter of a new export: the packaged shim execs ``python3 -m
    carlos_ctl.cli``; the shell shim itself and a later download are not it."""
    if len(command) < 4 or not Path(os.fsdecode(command[0])).name.startswith("python"):
        return False
    try:
        module = command.index(b"-m")
    except ValueError:
        return False
    return (
        command[module + 1 : module + 3] == [b"carlos_ctl.cli", b"cds-export"]
        and b"--download" not in command
        # Between fork and exec the supervisor's child still carries the supervisor's image.
        and b"--supervise" not in command
    )


def descendants(root: int) -> dict[int, list[bytes]]:
    """Command lines of the live descendants of one owned supervisor."""
    parents = {}
    for entry in Path("/proc").iterdir():
        if not entry.name.isdecimal():
            continue
        try:
            fields = (entry / "stat").read_text().rsplit(")", 1)[1].split()
            parents[int(entry.name)] = int(fields[1])
        except (FileNotFoundError, ProcessLookupError):
            pass
    selected = {root}
    for _ in range(8):
        selected |= {pid for pid, parent in parents.items() if parent in selected}
    commands = {}
    for pid in selected - {root}:
        try:
            commands[pid] = Path(f"/proc/{pid}/cmdline").read_bytes().split(b"\0")
        except (FileNotFoundError, ProcessLookupError):
            pass
    return commands


def export_events(path: Path) -> tuple[dict, str | None]:
    """Finite projection of one CLI log, and the accepted handle kept private to the harness."""
    counts = Counter()
    prefixes = Counter()
    accepted = []
    result = None
    technical = []
    technical_errors = []
    with path.open(encoding="utf-8") as stream:
        for number, line in enumerate(stream):
            if number >= 200000 or len(line) > 65536:
                raise RuntimeError("bounded export operator log contract was exceeded")
            if line.startswith("{"):
                row = json.loads(line)
                event = row.get("event") if isinstance(row, dict) else None
                if event not in EXPORT_EVENTS:
                    raise RuntimeError("unexpected export operator JSON")
                counts[event] += 1
                if event == "ACCEPTED":
                    handle = row.get("runId")
                    if not isinstance(handle, str) or not UUID.fullmatch(handle):
                        raise RuntimeError("invalid durable export handle")
                    accepted.append(handle)
                if event == "RESULT":
                    result = {key: row.get(key) for key in RESULT_FIELDS}
                    code = result.get("safeCode")
                    if code is not None and not (
                        isinstance(code, str) and re.fullmatch(r"CDS_[A-Z0-9_]{1,90}", code)
                    ):
                        result["safeCode"] = "UNRECOGNIZED"
                    for key in ("totalPatients", "processedPatients", "blockedPatients"):
                        if result.get(key) is not None and type(result[key]) is not int:
                            result[key] = None
                continue
            prefix = re.match(r"^(?:carlos-ctl: )?(CDS_[A-Z0-9_]{1,64}):", line)
            if prefix:
                prefixes[prefix[1]] += 1
            if line.startswith("CDS_TECHNICAL: ") and len(technical) < 4:
                try:
                    technical.append(
                        GATE.technical_failure_projection(
                            json.loads(line.removeprefix("CDS_TECHNICAL: "))
                        )
                    )
                except Exception as failure:  # noqa: BLE001 -- evidence must not hide the outcome
                    if len(technical_errors) < 4:
                        technical_errors.append(GATE.safe_failure(failure))
    if len(set(accepted)) > 1:
        raise RuntimeError("ambiguous durable export handles; explicit reconciliation required")
    projection = {
        "eventCounts": dict(sorted(counts.items())),
        "accepted": len(set(accepted)),
        "result": result,
        "diagnosticPrefixes": dict(sorted(prefixes.items())),
        "technicalFailureEvidence": technical,
        "technicalEvidenceErrors": technical_errors,
        "privateLogBytes": path.stat().st_size,
        "privateLogSha256": GATE.digest(path),
    }
    return projection, (accepted[0] if accepted else None)


def package_counts(
    path: Path, *, maximum_members: int = 4096, maximum_bytes: int = 1 << 30
) -> dict:
    """Independently count patient records, notes and results in one decrypted package."""
    from defusedxml.ElementTree import iterparse

    counted = Counter()
    xml_members = 0
    expanded = 0
    with zipfile.ZipFile(path) as archive:
        members = archive.infolist()
        if not members or len(members) > maximum_members:
            raise RuntimeError("package member inventory is outside its bound")
        for member in members:
            name = member.filename
            if name.startswith("/") or ".." in PurePosixPath(name).parts:
                raise RuntimeError("package contains an unsafe member")
            expanded += member.file_size
            if expanded > maximum_bytes:
                raise RuntimeError("package expands beyond its bound")
            if member.is_dir() or not name.endswith(".xml"):
                continue
            xml_members += 1
            with archive.open(member) as stream:
                for _, element in iterparse(stream, events=("end",)):
                    tag = element.tag.rsplit("}", 1)[-1] if element.tag.startswith("{cds}") else None
                    if tag in ("PatientRecord", "ClinicalNotes", "LaboratoryResults"):
                        counted[tag] += 1
                        if tag != "PatientRecord":
                            element.clear()
    return {
        "members": len(members),
        "xmlMembers": xml_members,
        "patientRecords": counted["PatientRecord"],
        "clinicalNotes": counted["ClinicalNotes"],
        "laboratoryResults": counted["LaboratoryResults"],
        "expandedBytes": expanded,
    }


