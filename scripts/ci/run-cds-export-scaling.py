"""Installed CDS export scaling gate: time, SQL and memory of carlos-ctl cds-export as charts grow.

Run as root in the disposable runtime that run-cds-performance-ci.py owns, after the import
fixture (CdsCliEngineFixture prepare) has written the installed configuration. The paired
installed carlos-ctl delegates every export to the real non-root service JVM; nothing here
replaces the engine, its configuration or its authorization.

Each profile exports one growth series of three cases, all synthetic FAKE- data. The
``patients`` series exports 1, 8 and 32 charts of one note and one laboratory result each; the
``charts`` series exports one chart of 128, 512 and 2048 notes and as many results. Each series
runs for two origins:

* ``native``: ordinary charts entered as the CARLOS screens store them (CdsExportScalingFixture
  seed): an admitted demographic, signed program-scoped encounter notes and uploaded HL7 results;
* ``imported``: the same sizes generated by the import harness's real-wire producer and
  imported first with ``carlos-ctl cds-import``, so the export takes the retained receipt and
  witness reconciliation path.

The four profiles (native-patients, native-charts, imported-patients, imported-charts) run as
separate CI jobs, so the long imported 2048-note chart does not serialize the others.

Every case is one foreground ``carlos-ctl cds-export`` measured on an exclusive server. A case
passes only if the job is READY with every selected patient processed and none held, the
decrypted package carries exactly the expected notes and results, and every budget below holds.
Public evidence is limited to counts, timings, resource receipts, classes and hashes: never
patient values, identifiers, run handles or paths.
"""

