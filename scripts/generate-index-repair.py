"""Generate the unpublished performance-index convergence migration.

Inputs are physical metadata from fresh Flyway reference databases (see
schema-contract.py). Never regenerate an already published migration.
"""
import argparse
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]


def literal(value):
    return "'" + value.replace("'", "''") + "'"


def generate(on, bc):
    indexes = {}
    for metadata in (on, bc):
        for row in metadata["indexes"]:
            indexes.setdefault((row[0], row[1]), {})[row[3]] = row
    files = list((ROOT / "database/mysql/migration").glob("*/V*performance_indexes*.sql"))
    files += list((ROOT / "database/mysql/migration").glob("*/V*consultation_request_indexes.sql"))
    files += list((ROOT / "database/mysql/migration").glob("*/V*bc_billingmaster_indexes.sql"))
    selected = set()
    for path in files:
        for name, table in re.findall(r"CREATE\s+(?:UNIQUE\s+)?INDEX\s+(?:IF\s+NOT\s+EXISTS\s+)?`?(\w+)`?\s+ON\s+`?(\w+)", path.read_text(), re.I):
            if (table, name) in indexes and name != "idx_providerExt_provider_no":
                selected.add((table, name))
    header = """-- Reconcile reviewed performance indexes by their complete definitions.
-- IF NOT EXISTS alone accepts a same-name, wrong-column or ignored index.
-- Fresh installs, upgraded installations and imports use the same decisions.
-- All shape/uniqueness guards run before the first index is changed.
-- No clinical rows or uniqueness constraints are rewritten. Stop all writers
-- and take a verified backup; multiple DDL statements are not one transaction.
-- Generated by scripts/generate-index-repair.py from fresh Flyway metadata.

DROP PROCEDURE IF EXISTS carlos_index_contract_1_0_59_6;
DELIMITER $$
CREATE PROCEDURE carlos_index_contract_1_0_59_6(
    IN expected_table VARCHAR(64), IN expected_index VARCHAR(64),
    IN expected_signature TEXT, IN required_columns TEXT, IN index_definition TEXT,
    IN table_required BOOLEAN, IN apply_change BOOLEAN)
SQL SECURITY INVOKER
body: BEGIN
    DECLARE actual_signature TEXT;
    DECLARE actual_unique INTEGER;
    DECLARE column_count INTEGER;
    DECLARE table_count INTEGER;
    DECLARE error_message VARCHAR(128);
    SELECT COUNT(*) INTO table_count FROM information_schema.tables
        WHERE table_schema = DATABASE() AND table_name = expected_table;
    IF table_count = 0 AND NOT table_required THEN LEAVE body; END IF;
    SELECT COUNT(*) INTO column_count FROM information_schema.columns
        WHERE table_schema = DATABASE() AND table_name = expected_table
          AND FIND_IN_SET(column_name, required_columns) > 0;
    IF table_count = 0 OR column_count <> 1 + LENGTH(required_columns) - LENGTH(REPLACE(required_columns, ',', '')) THEN
        SET error_message = CONCAT('Resolve missing index columns in ', expected_table, ' before upgrade');
        SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = error_message;
    END IF;
    SELECT CONCAT(MIN(non_unique), ':', MIN(index_type), ':', MIN(ignored), ':',
        GROUP_CONCAT(CONCAT(HEX(column_name), ':', COALESCE(sub_part, 0), ':', COALESCE(collation, '-'))
                     ORDER BY seq_in_index SEPARATOR ',')), MIN(non_unique)
        INTO actual_signature, actual_unique
    FROM information_schema.statistics
    WHERE table_schema = DATABASE() AND table_name = expected_table AND index_name = expected_index;
    IF actual_signature = expected_signature THEN LEAVE body; END IF;
    IF actual_unique = 0 THEN
        SET error_message = CONCAT('Unexpected unique index ', expected_table, '.', expected_index, '; review before upgrade');
        SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = error_message;
    END IF;
    IF apply_change THEN
        SET @carlos_index_ddl = CONCAT('ALTER TABLE `', REPLACE(expected_table, '`', '``'), '` ',
            IF(actual_signature IS NULL, '', CONCAT('DROP INDEX `', REPLACE(expected_index, '`', '``'), '`, ')),
            'ADD INDEX `', REPLACE(expected_index, '`', '``'), '` ', index_definition);
        PREPARE carlos_index_statement FROM @carlos_index_ddl;
        EXECUTE carlos_index_statement;
        DEALLOCATE PREPARE carlos_index_statement;
    END IF;
END$$
DELIMITER ;

"""
    output = header
    for apply in (0, 1):
        output += "-- " + ("Validate the whole repair set." if not apply else "Apply only missing or incorrect definitions.") + "\n"
        for table, name in sorted(selected):
            rows = [value for _, value in sorted(indexes[(table, name)].items())]
            if any(row[2] != 1 or row[7] != "BTREE" for row in rows):
                raise ValueError("performance repair must not rewrite a unique or non-BTREE index")
            signature = "1:BTREE:NO:" + ",".join("{0}:{1}:{2}".format(row[4].encode().hex().upper(), row[6] or 0, row[5] or "-") for row in rows)
            definition = "(" + ", ".join("`{0}`{1}{2}".format(row[4], "(" + str(row[6]) + ")" if row[6] else "", " DESC" if row[5] == "D" else "") for row in rows) + ") USING BTREE"
            required = int(table in {row[0] for row in on["tables"]} and table in {row[0] for row in bc["tables"]})
            arguments = [literal(table), literal(name), literal(signature), literal(",".join(row[4] for row in rows)), literal(definition), str(required), str(apply)]
            output += "CALL carlos_index_contract_1_0_59_6(" + ", ".join(arguments) + ");\n"
        output += "\n"
    output += "DROP PROCEDURE carlos_index_contract_1_0_59_6;\n"
    output += """
-- V1.0.52 now supplies a full provider_no unique index. The old plain
-- providerExt index has the same key width/order and adds write/storage cost.
SET @carlos_provider_cover = (
    SELECT COUNT(*) FROM (
        SELECT index_name FROM information_schema.statistics
        WHERE table_schema = DATABASE() AND table_name = 'providerExt'
        GROUP BY index_name
        HAVING COUNT(*) = 1 AND MIN(non_unique) = 0 AND MIN(column_name) = 'provider_no'
           AND MIN(sub_part) IS NULL AND MIN(index_type) = 'BTREE' AND MIN(ignored) = 'NO'
    ) covering_provider_indexes
);
SET @carlos_provider_redundant = (
    SELECT COUNT(*) = 1 AND MIN(column_name) = 'provider_no' AND MIN(non_unique) = 1
        AND MIN(sub_part) IS NULL AND MIN(index_type) = 'BTREE'
    FROM information_schema.statistics
    WHERE table_schema = DATABASE() AND table_name = 'providerExt'
      AND index_name = 'idx_providerExt_provider_no'
);
SET @carlos_index_ddl = IF(@carlos_provider_cover > 0 AND @carlos_provider_redundant,
    'ALTER TABLE providerExt DROP INDEX idx_providerExt_provider_no', 'SELECT 1');
PREPARE carlos_index_statement FROM @carlos_index_ddl;
EXECUTE carlos_index_statement;
DEALLOCATE PREPARE carlos_index_statement;

-- The canonical conditional unique key added in V1.0.54 supplies the full
-- demographic_no leading key. Retain the plain index on an adopted site
-- without that replacement; never introduce uniqueness on its data here.
SET @carlos_demo_cover = (
    SELECT COUNT(*) FROM (
        SELECT index_name FROM information_schema.statistics
        WHERE table_schema = DATABASE() AND table_name = 'demographicExt'
        GROUP BY index_name
        HAVING COUNT(*) = 2 AND MIN(non_unique) = 0 AND MIN(ignored) = 'NO'
           AND SUM(seq_in_index = 1 AND column_name = 'demographic_no' AND sub_part IS NULL) = 1
           AND SUM(seq_in_index = 2 AND column_name = 'dashboard_single_value_key' AND sub_part IS NULL) = 1
    ) covering_demo_indexes
);
SET @carlos_demo_redundant = (
    SELECT COUNT(*) = 1 AND MIN(column_name) = 'demographic_no' AND MIN(non_unique) = 1
        AND MIN(sub_part) IS NULL AND MIN(index_type) = 'BTREE'
    FROM information_schema.statistics
    WHERE table_schema = DATABASE() AND table_name = 'demographicExt' AND index_name = 'demographic_no'
);
SET @carlos_index_ddl = IF(@carlos_demo_cover > 0 AND @carlos_demo_redundant,
    'ALTER TABLE demographicExt DROP INDEX demographic_no', 'SELECT 1');
PREPARE carlos_index_statement FROM @carlos_index_ddl;
EXECUTE carlos_index_statement;
DEALLOCATE PREPARE carlos_index_statement;
"""
    return output


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--on", required=True, type=Path)
    parser.add_argument("--bc", required=True, type=Path)
    parser.add_argument("--output", required=True, type=Path)
    args = parser.parse_args()
    inputs = [json.loads(path.read_text()) for path in (args.on, args.bc)]
    inputs = [value.get("schema", value) for value in inputs]
    args.output.write_text(generate(*inputs))


if __name__ == "__main__":
    main()
