    public static final class Source {
        private final String originalSha256;
        private final String extractedTextSha256;
        private final String fingerprint;
        private final ClinicalSummaryTextExtractor.Extract extraction;

        private Source(Scope scope, Metadata metadata, byte[] bytes,
                ClinicalSummaryTextExtractor.Extract extraction) {
            this.extraction = extraction;
            originalSha256 = hash(bytes);
            extractedTextSha256 = hashText(extraction.text());
            fingerprint = fingerprint("source", scope.clinicId(), Integer.toString(scope.patientId()),
                    Integer.toString(scope.documentId()), metadata.filename(), metadata.contentType(),
                    metadata.title(), Objects.toString(metadata.updatedAtMillis(), null), originalSha256,
                    extractedTextSha256, Boolean.toString(extraction.complete()), extraction.reason());
        }

        public String originalSha256() { return originalSha256; }
        public String extractedTextSha256() { return extractedTextSha256; }
        /** Text derived from the captured bytes, for an already authorized caller's generation. */
        public ClinicalSummaryTextExtractor.Extract extraction() { return extraction; }
        @Override public String toString() { return "SummaryReviewSource[REDACTED]"; }
    }

    /** Capture bytes supplied by the authorized bounded document loader, never a browser hash. */
    public static Source capture(Scope scope, Metadata metadata, byte[] originalBytes) {
        try (CapturedSource captured = captureOwned(scope, metadata, originalBytes)) {
            return captured.source();
        }
    }

    /**
     * Optional, bounded ownership of the exact bytes used for extraction and source hashing.
     * A future original-document consumer can take an independent copy instead of reloading or
     * rendering different bytes after review. This performs no signature or access verification,
     * creates no session store, and grants no permission to review or send a document.
     */
    public static CapturedSource captureOwned(Scope scope, Metadata metadata, byte[] originalBytes) {
        Objects.requireNonNull(scope);
        Objects.requireNonNull(metadata);
        if (originalBytes == null || originalBytes.length == 0 || originalBytes.length > MAX_SOURCE_BYTES) {
            throw invalid();
        }
        byte[] snapshot = originalBytes.clone();
        boolean retained = false;
        try {
            // Derive text from these same copied bytes; a caller cannot pair a hash with unrelated text.
            var extraction = ClinicalSummaryTextExtractor.bytes(snapshot, metadata.contentType());
            var captured = new CapturedSource(new Source(scope, metadata, snapshot, extraction), snapshot);
            retained = true;
            return captured;
        } catch (java.io.IOException failure) {
            throw new IllegalArgumentException("Source text is unavailable.");
        } finally {
            if (!retained) Arrays.fill(snapshot, (byte) 0);
        }
    }

    /**
     * Bytes-only custody, not a source-freshness or authorization capability. All byte access
     * returns independent copies. Closing prevents new access through this object and clears its
     * owned array; it cannot erase escaped copies, immutable extracted text (including extractor
     * caches), or invalidate a previously obtained Source, Draft or Approval. Future consumers
     * must independently recheck access, source freshness and the intended delivery bytes.
     */
    public static final class CapturedSource implements AutoCloseable {
        private Source source;
        private byte[] bytes;

        private CapturedSource(Source source, byte[] bytes) {
            this.source = source;
            this.bytes = bytes;
        }

        /** Existing immutable hash/text evidence; obtaining it does not authorize later use. */
        public synchronized Source source() {
            requireOpen();
            return source;
        }

        /** An independent exact copy, available only while this custody object is open. */
        public synchronized byte[] copyBytes() {
            requireOpen();
            return bytes.clone();
        }

        private void requireOpen() {
            if (bytes == null) throw new IllegalStateException("Captured source is closed.");
        }

        /** Idempotent disposal of this object's array only; escaped evidence/copies are unaffected. */
        @Override public synchronized void close() {
            if (bytes != null) {
                Arrays.fill(bytes, (byte) 0);
                bytes = null;
                source = null;
            }
        }

        @Override public String toString() { return "CapturedSummarySource[REDACTED]"; }
    }

    public static final class Draft {
        private final UUID id = UUID.randomUUID();
        private final Source source;
        private final DocumentSummary summary;
        private final Instant generatedAt;
        private final String modelIdentity;
        private final String language;
        private final Instant revisedAt;
        private final String version;

        private Draft(Source source, DocumentSummary summary, String modelIdentity, String language, Instant generatedAt, Instant revisedAt) {
            this.source = source;
            this.summary = summary;
            this.generatedAt = generatedAt;
            this.modelIdentity = modelIdentity;
            this.language = language;
            this.revisedAt = revisedAt;
            // These values are already validated strings/lists. Hash each value with an unambiguous
            // length frame, preserving point/excerpt order and exact Unicode, not normalized prose.
            String pointsHash = fingerprint("points", ClinicalSummaryAgentProtocol.JSON.valueToTree(summary.points()).toString());
            version = fingerprint("draft", id.toString(), source.fingerprint, summary.overview(), pointsHash,
                    modelIdentity, language, generatedAt.toString(), noticeVersion(language), noticeHeading(language), noticeBody(language),
                    Objects.toString(revisedAt, null));
        }

        public UUID id() { return id; }
        public String version() { return version; }
        public Instant generatedAt() { return generatedAt; }
        public Instant revisedAt() { return revisedAt; }
        public String modelIdentity() { return modelIdentity; }
        public String language() { return language; }
        public DocumentSummary summary() { return summary; }
        public boolean extractionComplete() { return source.extraction.complete(); }
        public String extractionDisclosure() { return source.extraction.reason(); }
        public String previewNotice() { return unreviewedNotice(language); }
        /** Revalidation alone never records review or changes the draft. */
        public void requireCurrent(Source currentSource) {
            if (currentSource == null || !source.fingerprint.equals(currentSource.fingerprint)) throw changed();
        }
        @Override public String toString() { return "DocumentSummaryDraft[REDACTED]"; }
    }

    /** Freeze an already generated result. This method makes no model call and records no review. */
    public Draft prepare(Source source, DocumentSummary summary, String modelIdentity, String language) {
        Objects.requireNonNull(source);
        Objects.requireNonNull(summary);
        label(modelIdentity, 240);
        // Only a reviewed, versioned notice ships: English, French, Spanish, Polish and Brazilian Portuguese. Never an automatic translation.
        if (!NOTICE_LANGUAGES.contains(language)) throw new IllegalArgumentException("Reviewed notice is unavailable for this language.");
        if (source.extraction.text().isBlank()) {
            throw new IllegalStateException("Readable source text is required for review.");
        }
        var value = ClinicalSummaryAgentProtocol.JSON.valueToTree(Map.of(
                "overview", summary.overview(), "points", summary.points()));
        DocumentSummaryService.validate(value, source.extraction.text());
        Instant generatedAt = now();
        return new Draft(source, new DocumentSummary(value), modelIdentity, language, generatedAt, null);
    }

    /**
     * Revise only existing text/removals; evidence and model-generation provenance remain server-owned.
     * The caller must authorize the current source and displayed draft before calling this method.
     * Empty results belong to the existing discard operation, not a different summary schema.
     */
    Draft revise(Draft prior, String overview, List<String> pointTexts, Set<Integer> removedPoints) {
        if (prior == null || overview == null || overview.length() > 4000
                || pointTexts == null || removedPoints == null) throw invalid();
        var existing = ClinicalSummaryAgentProtocol.JSON.valueToTree(prior.summary.points());
        int count = existing.size();
        if (pointTexts.size() != count || removedPoints.size() >= count
                || removedPoints.stream().anyMatch(index -> index == null || index < 0 || index >= count)
                || pointTexts.stream().anyMatch(text -> text == null || text.length() > 2000)) throw invalid();
        var value = ClinicalSummaryAgentProtocol.JSON.createObjectNode().put("overview", overview);
        var points = value.putArray("points");
        for (int index = 0; index < count; index++) {
            if (!removedPoints.contains(index)) {
                var point = points.addObject().put("text", pointTexts.get(index));
                point.set("evidence", existing.get(index).get("evidence").deepCopy());
            }
        }
        DocumentSummaryService.validate(value, prior.source.extraction.text());
        Instant revisedAt = now();
        if (revisedAt.isBefore(prior.generatedAt)
                || (prior.revisedAt != null && revisedAt.isBefore(prior.revisedAt))) throw changed();
        return new Draft(prior.source, new DocumentSummary(value), prior.modelIdentity, prior.language,
                prior.generatedAt, revisedAt);
    }

    public static final class Approval {
        private final Draft draft;
        private final String reviewerId;
        private final String reviewerName;
        private final Instant reviewedAt;

        private Approval(Draft draft, String reviewerId, String reviewerName, Instant reviewedAt) {
            this.draft = draft;
            this.reviewerId = reviewerId;
            this.reviewerName = reviewerName;
            this.reviewedAt = reviewedAt;
        }

        public String reviewerId() { return reviewerId; }
        public Instant reviewedAt() { return reviewedAt; }
        public String summaryVersion() { return draft.version; }
        public String sourceSha256() { return draft.source.originalSha256; }
        public Instant generatedAt() { return draft.generatedAt; }
        public Instant revisedAt() { return draft.revisedAt; }
        public DocumentSummary summary() { return draft.summary; }
        /** The language the summary was written in, for the reading-aid artifact; never the reviewer. */
        public String language() { return draft.language; }
        public boolean extractionComplete() { return draft.extractionComplete(); }
        public String extractionDisclosure() { return draft.extractionDisclosure(); }
        public String patientNotice() {
            return notice(known(draft.language), reviewed(draft.language, reviewerName, reviewedAt));
        }

        /** Future send callers must freshly authorize/load both inputs; this does not authorize sending. */
        public void requireCurrent(Source currentSource, Draft currentDraft) {
            if (currentSource == null || currentDraft == null
                    || !draft.source.fingerprint.equals(currentSource.fingerprint)
                    || !draft.version.equals(currentDraft.version)) throw changed();
        }
        @Override public String toString() { return "DocumentSummaryApproval[REDACTED]"; }
    }

    /**
     * Reviewer comes only from the caller's authenticated server session; time comes from this
     * service's server clock. There is no reviewer/time parameter or deserialization constructor.
     * The caller must independently verify clinician privilege and current source access.
     */
    public Approval approve(Draft draft, UUID displayedDraftId, Source currentSource,
            LoggedInInfo authenticatedActor, boolean approveOriginalSummaryAndDisclosures) {
        if (!approveOriginalSummaryAndDisclosures) {
            throw new IllegalStateException("Explicit review of the original, exact summary and disclosures is required.");
        }
        if (draft == null || currentSource == null || !draft.id.equals(displayedDraftId)
                || !draft.source.fingerprint.equals(currentSource.fingerprint)) throw changed();
        if (authenticatedActor == null || authenticatedActor.getLoggedInProvider() == null) {
            throw new SecurityException("Authenticated reviewer required.");
        }
        var provider = authenticatedActor.getLoggedInProvider();
        String reviewerId = provider.getProviderNo();
        String reviewerName = provider.getFormattedName();
        label(reviewerId, 64);
        label(reviewerName, 240);
        Instant reviewedAt = now();
        if (reviewedAt.isBefore(draft.generatedAt)
                || (draft.revisedAt != null && reviewedAt.isBefore(draft.revisedAt))) throw changed();
        return new Approval(draft, reviewerId, reviewerName, reviewedAt);
    }

    private Instant now() {
        Instant value = clock.instant();
        if (value.isBefore(Instant.EPOCH)) throw invalid();
        return value;
    }

    public static String unreviewedNotice() { return unreviewedNotice("en"); }

    /** The unreviewed notice in a notice language; any other value renders English. */
    public static String unreviewedNotice(String language) {
        String known = known(language);
        return notice(known, unconfirmed(known));
    }

    /** The patient notice's language for a record: {@link #noticeLanguage(String, String)} with no spoken language. */
    public static String noticeLanguage(String officialLanguage) { return noticeLanguage(officialLanguage, null); }

    /**
     * The notice language for a patient record ("en", "fr", "es", "pl" or "pt-BR"). French when the
     * official language says French (the values "English"/"French", the import codes and tags such as
     * "fr-CA"); otherwise the spoken language on file when it names Spanish, Polish or Portuguese;
     * English for everything else. Exact tokens only, never a prefix match ("Frisian", "free text",
     * "Spanglish" are English). Portuguese of any region gets the Brazilian Portuguese notice, the only
     * one reviewed. The sender cannot choose it per send, and neither can the browser.
     */
    public static String noticeLanguage(String officialLanguage, String spokenLanguage) {
        if (matches(officialLanguage, "fr|fre|fra|fr[-_][a-z0-9]{2,8}|french|français|francais")) return "fr";
        if (matches(spokenLanguage, "es|spa|es[-_][a-z0-9]{2,8}|spanish|spanish; castilian|castilian|español|espanol|castellano")) return "es";
        if (matches(spokenLanguage, "pl|pol|pl[-_][a-z0-9]{2,8}|polish|polski")) return "pl";
        if (matches(spokenLanguage, "pt|por|pt[-_][a-z0-9]{2,8}|portuguese|português|portugues|brazilian portuguese")) return "pt-BR";
        return "en";
    }

    private static boolean matches(String value, String tokens) {
        if (value == null) return false;
        // Tolerate the list's "^" mark for a preferred entry and surrounding space; nothing else.
        return value.strip().replaceFirst("^\\^", "").toLowerCase(java.util.Locale.ROOT).matches(tokens);
    }

