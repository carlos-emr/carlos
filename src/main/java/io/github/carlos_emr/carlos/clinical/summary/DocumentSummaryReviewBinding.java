    /** One language per notice: heading, status line and body all from the same set. */
    private static String notice(String language, String reviewStatus) {
        return noticeHeading(language) + statusLabel(language) + reviewStatus + "\n\n" + noticeBody(language);
    }

    private static String hash(byte[] bytes) { return HexFormat.of().formatHex(digest().digest(bytes)); }

    private static String hashText(String text) {
        try {
            MessageDigest digest = digest();
            digest.update(StandardCharsets.UTF_8.newEncoder().encode(java.nio.CharBuffer.wrap(text)));
            return HexFormat.of().formatHex(digest.digest());
        } catch (CharacterCodingException invalidUnicode) { throw invalid(); }
    }

    private static String fingerprint(String purpose, String... values) {
        MessageDigest digest = digest();
        update(digest, "carlos/summary-review/1");
        update(digest, purpose);
        for (String value : values) update(digest, value);
        return HexFormat.of().formatHex(digest.digest());
    }

    private static void update(MessageDigest digest, String value) {
        if (value == null) { digest.update(ByteBuffer.allocate(4).putInt(-1).array()); return; }
        try {
            ByteBuffer encoded = StandardCharsets.UTF_8.newEncoder().encode(java.nio.CharBuffer.wrap(value));
            digest.update(ByteBuffer.allocate(4).putInt(encoded.remaining()).array());
            digest.update(encoded);
        } catch (CharacterCodingException invalidUnicode) { throw invalid(); }
    }

    private static MessageDigest digest() {
        try { return MessageDigest.getInstance("SHA-256"); }
        catch (NoSuchAlgorithmException impossible) { throw new IllegalStateException("SHA-256 unavailable", impossible); }
    }

    private static void label(String value, int maximum) {
        if (value == null || value.isBlank() || value.length() > maximum
                || value.codePoints().anyMatch(Character::isISOControl)) throw invalid();
    }
    private static IllegalArgumentException invalid() { return new IllegalArgumentException("Invalid summary review data."); }
    private static IllegalStateException changed() { return new IllegalStateException("The source or draft changed; review the current draft."); }
