package io.github.carlos_emr.carlos.webserv.rest.util;

import java.io.IOException;
import java.text.SimpleDateFormat;
import java.util.Date;
import java.util.Locale;

import com.fasterxml.jackson.core.JsonGenerator;
import com.fasterxml.jackson.databind.JsonSerializer;
import com.fasterxml.jackson.databind.SerializerProvider;

/** Writes an explicitly date-only property in the server's local calendar. */
public class DateOnlySerializer extends JsonSerializer<Date> {
    @Override
    public void serialize(Date value, JsonGenerator generator, SerializerProvider provider) throws IOException {
        // Keep the formatter local: SimpleDateFormat is mutable and not thread-safe.
        // Match Demographic's GregorianCalendar and SmartDateDeserializer's local date.
        generator.writeString(new SimpleDateFormat("yyyy-MM-dd", Locale.ROOT).format(value));
    }
}
