/*
 * Confirm-before-submit for the Appointment Settings tabs (Statuses and Locations).
 *
 * A form marked data-confirm="<question>" asks the question when it is submitted. Cancelling sends
 * nothing: the submit is stopped before any other submit handler runs, so a disable or a reset that
 * cannot be undone from the page never happens by accident.
 */
(function () {
    document.querySelectorAll('form[data-confirm]').forEach(function (form) {
        form.addEventListener('submit', function (event) {
            if (!window.confirm(form.dataset.confirm)) {
                event.preventDefault();
                event.stopImmediatePropagation();
            }
        });
    });
})();
