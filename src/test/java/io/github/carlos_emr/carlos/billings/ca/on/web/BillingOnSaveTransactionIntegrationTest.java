/** Real database commit/rollback at the action's transaction boundary, including token retry. */
@Tag("integration") @Tag("billing")
class BillingOnSaveTransactionIntegrationTest extends CarlosUnitTestBase {
    @ParameterizedTest
    @ValueSource(strings={"appointment-exception","appointment-false","cleanup-exception","cleanup-refused"})
    void shouldRollbackWholeOperationAndAllowOneSuccessfulRetry_afterDependentWriteFailure(String failure) {
        var dataSource=new JdbcDataSource();dataSource.setURL("jdbc:h2:mem:"+UUID.randomUUID()+";DB_CLOSE_DELAY=-1");
        var jdbc=new JdbcTemplate(dataSource);
        jdbc.execute("create table claims (id integer generated by default as identity primary key)");
        jdbc.execute("create table appointment_state (id int primary key, state varchar(10))");
        jdbc.execute("create table old_bill_state (id int primary key, state varchar(10))");
        jdbc.update("insert into appointment_state values (880,'t')");
        jdbc.update("insert into old_bill_state values (9,'O')");
        var transactions=new DataSourceTransactionManager(dataSource);
        var security=mock(SecurityInfoManager.class);when(security.hasPrivilege(any(),eq("_billing"),eq("w"),isNull())).thenReturn(true);
        var bills=mock(BillingDao.class);var service=mock(BillingClaimSubmissionService.class);
        var request=new MockHttpServletRequest("POST","/billing/CA/ON/billingONSave");
        var response=new MockHttpServletResponse();var user=mock(LoggedInInfo.class);
        when(user.getLoggedInProviderNo()).thenReturn("999998");
        LoggedInInfo.setLoggedInInfoIntoSession(request.getSession(),user);
        request.setParameter("demographic_no","101");request.setParameter("billingAction","SAVE");
        request.setParameter("xml_billtype","HCP");request.setParameter("appointment_no","880");
        request.setParameter("billNo_old","9");request.setParameter("billStatus_old","O");
        request.setParameter(FormSubmissionGuard.PARAMETER,FormSubmissionGuard.issue(request.getSession(),
                FormSubmissionGuard.Scope.BILLING_ON_SAVE,"101"));
        when(service.getSubmission(request)).thenReturn(new BillingClaimSubmissionService.BillingClaimSubmission(
                new io.github.carlos_emr.carlos.billings.ca.on.dto.BillingClaimHeaderDto(),List.of()));
        when(service.saveBillingWithExtAndPayee(any(),eq(request),eq("HCP"),any())).thenAnswer(call->{
            jdbc.update("insert into claims default values");
            return new BillingClaimSubmissionService.SaveResult(true,jdbc.queryForObject("select max(id) from claims",Integer.class));
        });
        when(service.getApptStatus("880")).thenReturn("t");var inject=new AtomicBoolean(true);
        when(service.updateApptStatus(eq("880"),any(),eq("999998"))).thenAnswer(call->{
            jdbc.update("update appointment_state set state='b' where id=880");
            if(failure.startsWith("appointment") && inject.getAndSet(false)) {
                if(failure.endsWith("false")) return false;
                throw new IllegalStateException("Synthetic appointment failure");
            }
            return true;
        });
        when(bills.find(9)).thenAnswer(call->{var bill=new Billing();bill.setStatus("O");return bill;});
        doAnswer(call->{
            jdbc.update("update old_bill_state set state='D' where id=9");
            if(failure.equals("cleanup-exception") && inject.getAndSet(false)) throw new IllegalStateException("Synthetic cleanup failure");
            return null;
        }).when(bills).merge(any());
        if(failure.equals("cleanup-refused")) request.setParameter("billStatus_old","B");
        var props=mock(CarlosProperties.class);when(props.getProperty("isNewONbilling","")).thenReturn("false");
        var action=new BillingOnSave2Action(security,mock(UserPropertyDAO.class),bills,service,
                mock(BillingCorrectionRecordService.class),transactions);
        try(var servlet=mockStatic(ServletActionContext.class);var properties=mockStatic(CarlosProperties.class)) {
            servlet.when(ServletActionContext::getRequest).thenReturn(request);
            servlet.when(ServletActionContext::getResponse).thenReturn(response);
            properties.when(CarlosProperties::getInstance).thenReturn(props);
            if(failure.endsWith("exception")) assertThatThrownBy(action::execute).isInstanceOf(IllegalStateException.class);
            else assertThat(action.execute()).isEqualTo("failure");
            assertThat(jdbc.queryForObject("select count(*) from claims",Integer.class)).isZero();
            assertThat(jdbc.queryForObject("select state from appointment_state where id=880",String.class)).isEqualTo("t");
            assertThat(jdbc.queryForObject("select state from old_bill_state where id=9",String.class)).isEqualTo("O");
            request.setParameter("billStatus_old","O");
            assertThat(action.execute()).isEqualTo("success");
            assertThat(action.execute()).isEqualTo("success");
            assertThat(jdbc.queryForObject("select count(*) from claims",Integer.class)).isEqualTo(1);
            assertThat(jdbc.queryForObject("select state from appointment_state where id=880",String.class)).isEqualTo("b");
            assertThat(jdbc.queryForObject("select state from old_bill_state where id=9",String.class)).isEqualTo("D");
            verify(service,times(2)).saveBillingWithExtAndPayee(any(),eq(request),eq("HCP"),any());
        } finally {jdbc.execute("drop all objects");}
    }
}
